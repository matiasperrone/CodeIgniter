<?php
/**
 * Regenerates tests/fixtures/encrypt.php: ciphertexts produced by the
 * mcrypt-based CI_Encrypt, used to prove that data encrypted by existing
 * installations stays decodable (backwards compatibility).
 *
 * Run it ONLY with the original, unmodified Encrypt library, on an
 * interpreter that has mcrypt:   php5.6 tests/tools/make_encrypt_fixtures.php
 */
require dirname(__FILE__).'/../lib/harness.php';
require dirname(__FILE__).'/../bootstrap.php';

$CI = get_instance();
$CI->load->library('encrypt');

$cases = array(
	array('name' => 'default cipher, ascii', 'plain' => 'The quick brown fox jumps over the lazy dog', 'key' => 'secret-key', 'cipher' => NULL, 'mode' => NULL),
	array('name' => 'default cipher, empty-ish', 'plain' => 'x', 'key' => 'another key', 'cipher' => NULL, 'mode' => NULL),
	array('name' => 'default cipher, utf-8', 'plain' => "Caf\xc3\xa9 \xe2\x82\xac \xe6\x97\xa5\xe6\x9c\xac\xe8\xaa\x9e", 'key' => 'ключ', 'cipher' => NULL, 'mode' => NULL),
	array('name' => 'default cipher, long text', 'plain' => str_repeat('0123456789abcdef', 40), 'key' => 'k', 'cipher' => NULL, 'mode' => NULL),
	array('name' => 'blowfish cbc', 'plain' => 'Blowfish payload', 'key' => 'bf-key', 'cipher' => MCRYPT_BLOWFISH, 'mode' => MCRYPT_MODE_CBC),
	array('name' => 'rijndael-128 cfb', 'plain' => 'AES 128 in CFB', 'key' => 'aes-key', 'cipher' => MCRYPT_RIJNDAEL_128, 'mode' => MCRYPT_MODE_CFB),
	array('name' => 'rijndael-256 ecb', 'plain' => 'ECB mode payload', 'key' => 'ecb-key', 'cipher' => MCRYPT_RIJNDAEL_256, 'mode' => MCRYPT_MODE_ECB),
);

$out = array();
foreach ($cases as $c)
{
	$enc = new CI_Encrypt();
	if ($c['cipher'] !== NULL)
	{
		$enc->set_cipher($c['cipher']);
		$enc->set_mode($c['mode']);
	}
	$c['encoded'] = $enc->encode($c['plain'], $c['key']);
	$out[] = $c;
}

$php = "<?php\n// Generated by tests/tools/make_encrypt_fixtures.php with PHP ".PHP_VERSION." (mcrypt). Do not edit.\nreturn ".var_export($out, TRUE).";\n";
file_put_contents(dirname(__FILE__).'/../fixtures/encrypt.php', $php);
echo 'wrote '.count($out)." fixtures\n";
